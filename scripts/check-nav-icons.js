'use strict';
/**
 * check-nav-icons.js — postbuild gate for the left-sidebar nav icons.
 *
 * Sidebar item icons are injected at runtime by the swizzled `src/theme/Root.js`,
 * which matches each TOP-LEVEL sidebar link's lowercased label against a
 * hard-coded `NAV_ICONS` map. An item gets an icon iff the map holds a key equal
 * to its label lowercased — exact string match, no slug or href fallback.
 *
 * So adding a new top-level page silently renders it with NO icon until someone
 * remembers to edit Root.js, and nothing anywhere says so. That has happened
 * four times: `Support` (added 2026-03-29) and `Offline docs` (2026-05-22) each
 * went ~6 and ~4 months unnoticed; `Async Loaders` (2026-06-13) and the two
 * advanced tutorials (2026-09-21) were caught only by eye. This gate turns that
 * silent, long-lived inconsistency into a loud build failure.
 *
 * It reads Docusaurus's OWN resolved sidebar output rather than re-deriving it:
 * four of the seven sidebars are `{type: 'autogenerated'}`, so `sidebars.js`
 * holds almost no labels — they come from the filesystem, `_category_.json`
 * files and each page's `sidebar_label`. The resolved tree is emitted to
 * `.docusaurus/**\/p/*.json` as `version.docsSidebars`, which is authoritative
 * and free.
 *
 * ORDERING: must run BEFORE scripts/build-offline-zip.js. That script performs a
 * SECOND `docusaurus build` (with the offline config), which rewrites
 * `.docusaurus` — run this after it and the gate audits the offline site's data
 * instead of the real one.
 *
 * Exit codes: 0 every top-level label has an icon · 1 one or more do not ·
 * 2 the instrument itself is broken (never a silent pass).
 */

const fs = require('fs');
const path = require('path');

const ROOT = process.argv[2] || path.resolve(__dirname, '..');
const SIDEBAR_DIR = path.join(ROOT, '.docusaurus/docusaurus-plugin-content-docs/default/p');
const ROOT_JS = path.join(ROOT, 'src/theme/Root.js');

/**
 * Labels that are deliberately icon-less. Add a label here ONLY when the
 * omission is a decision; the default expectation is that every top-level item
 * carries an icon. Kept empty on purpose — an entry here should need a reason.
 */
const ALLOW_WITHOUT_ICON = new Set([]);

function fail(msg) {
  console.error('[nav-icons] ' + msg);
  process.exit(2);
}

// ── resolved sidebars ────────────────────────────────────────────────────────
if (!fs.existsSync(SIDEBAR_DIR)) {
  fail('no ' + path.relative(ROOT, SIDEBAR_DIR) + ' — this gate runs after `docusaurus build`.');
}

// `.docusaurus` accumulates STALE route files across builds, and several are
// named docs-*.json, so neither "first readdir hit" nor a filename glob is safe:
// an early version of this gate silently audited a 121-day-old snapshot and
// under-reported. Select by content, then take the NEWEST.
const candidates = [];
for (const name of fs.readdirSync(SIDEBAR_DIR)) {
  if (!name.endsWith('.json')) continue;
  const file = path.join(SIDEBAR_DIR, name);
  let parsed;
  try {
    parsed = JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (err) {
    continue; // not every route payload is ours to read
  }
  const sidebars = parsed && parsed.version && parsed.version.docsSidebars;
  if (sidebars && Object.keys(sidebars).length) {
    candidates.push({ name: name, sidebars: sidebars, mtime: fs.statSync(file).mtimeMs });
  }
}
if (!candidates.length) fail('no `version.docsSidebars` in any route payload — cannot read the sidebar structure.');
candidates.sort(function (a, b) { return b.mtime - a.mtime; });
const chosen = candidates[0];

// ── NAV_ICONS keys ───────────────────────────────────────────────────────────
if (!fs.existsSync(ROOT_JS)) fail('missing ' + path.relative(ROOT, ROOT_JS));
const lines = fs.readFileSync(ROOT_JS, 'utf8').split('\n');
const start = lines.findIndex(function (l) { return l.startsWith('const NAV_ICONS'); });
const end = lines.findIndex(function (l, i) { return i > start && l.trimEnd() === '};'; });
if (start < 0 || end < 0) fail('could not bound the NAV_ICONS object in Root.js — did its shape change?');

const keys = new Set();
for (const line of lines.slice(start + 1, end)) {
  const m = line.match(/^\s*'([^']+)'\s*:/);
  if (m) keys.add(m[1]);
}
// A map that parses to nothing would pass this gate vacuously for every label.
if (!keys.size) fail('parsed 0 keys from NAV_ICONS — the parser is broken, not the map.');

// ── compare ──────────────────────────────────────────────────────────────────
let total = 0;
const missing = [];
for (const sidebarName of Object.keys(chosen.sidebars)) {
  for (const item of chosen.sidebars[sidebarName]) {
    if (!item || !item.label) continue;
    total += 1;
    const key = item.label.toLowerCase();
    if (!keys.has(key) && !ALLOW_WITHOUT_ICON.has(item.label)) {
      missing.push({ sidebar: sidebarName, label: item.label, key: key });
    }
  }
}

console.log(
  '[nav-icons] ' + total + ' top-level items across ' + Object.keys(chosen.sidebars).length +
  ' sidebars, ' + keys.size + ' icon keys (read from ' + chosen.name + ')'
);

if (!missing.length) {
  console.log('[nav-icons] every top-level sidebar item has an icon.');
  process.exit(0);
}

console.error('');
console.error('[nav-icons] ' + missing.length + ' top-level sidebar item(s) have NO icon:');
for (const m of missing) {
  console.error('  ' + m.sidebar + ' -> "' + m.label + '"   (needs NAV_ICONS key: \'' + m.key + '\')');
}
console.error('');
console.error('[nav-icons] Add an entry to NAV_ICONS in src/theme/Root.js — a 24x24');
console.error('[nav-icons] stroke="currentColor" glyph, visually distinct from its siblings.');
console.error('[nav-icons] If an item is deliberately icon-less, add its label to');
console.error('[nav-icons] ALLOW_WITHOUT_ICON in this file, with a reason.');
process.exit(1);
